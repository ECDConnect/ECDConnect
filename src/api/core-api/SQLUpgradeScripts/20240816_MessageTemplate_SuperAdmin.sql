MORE ABOUT ECD CONNECT...<br>
ECD Connect is an extensive and sophisticated licence-free, open-source, customisable digital platform. The platform includes web apps for principals, practitioners and field-support staff, that are designed for low-end smartphones, require minimal data, and can be used offline for up to 30 days. It also includes a head office admin portal for content, user and data management.<br><br>

What are ECD Connect’s objectives?<br><br>
<ol>
<li>Reduce practitioners’ administrative and cognitive load</li>
<li>Give practitioners meaningful feedback and a way to connect to their community of practice</li>
<li>Equip organisations working in the ECD sector to monitor, support and respond to their programmes</li>
</ol>

What does ECD Connect offer to practitioners?<br>
As a digital work companion, ECD Connect provides early educators with a range of tools to assist them in their jobs, including:<br><br>

<ul>
<li>Classroom management tools, such as multilingual educational resources, daily programmes, attendance trackers, assessment and other pedagogical tools.</li>
<li>Business management tools, such as income and expense trackers, calendar and scheduling, venue and other checklists.</li>
<li>In-app courses for ongoing professional development.</li>
<li>Direct line of feedback and support.</li>
<li>Connection to community of practice and incentives programmes.</li>
</ul>

The platform equips practitioners to be more effective in their roles and to develop both as individuals and as a collective. Research in the field has shown that by raising standards of professionalism and improving outcomes, practitioners receive greater recognition for their work and increased demand for their services, allowing them to generate more value for themselves and help to ensure that the critical work they do is financially sustainable.<br>
If more competent practitioners remain in their line of work, the faster the sector will be able to close the gap to achieving universal access to quality ECD programmes.<br>
